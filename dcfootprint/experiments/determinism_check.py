"""Compare two pipeline runs file by file (determinism check for a canonical snapshot).

Each run directory holds the `results/` and `outputs/` trees copied after a clean run (outputs/ and
the SARIMA forecast caches moved aside first). Text results (csv, json, md) must be byte-identical;
parquet outputs are compared as tables (pandas `equals`), since parquet files carry writer metadata.
Figures (png) are not compared: matplotlib output is not byte-stable and every number in them is in a
compared table. Snapshots of earlier rounds (round*_final/) are skipped.

    python dcfootprint/experiments/determinism_check.py <run1> <run2> <out.md>
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

TEXT = {".csv", ".json", ".md"}


def files(root: Path) -> dict[str, Path]:
    out = {}
    for p in root.rglob("*"):
        rel = p.relative_to(root).as_posix()
        if p.is_file() and not any(part.startswith("round") and part.endswith("_final") for part in p.parts) \
                and p.suffix in TEXT | {".parquet"}:
            out[rel] = p
    return out


def main(a: Path, b: Path, out: Path):
    fa, fb = {}, {}
    for sub in ("results", "outputs"):
        fa |= {f"{sub}/{k}": v for k, v in files(a / sub).items()}
        fb |= {f"{sub}/{k}": v for k, v in files(b / sub).items()}
    only_a, only_b = sorted(set(fa) - set(fb)), sorted(set(fb) - set(fa))
    differ, n_text, n_pq = [], 0, 0
    for k in sorted(set(fa) & set(fb)):
        if k.endswith(".parquet"):
            n_pq += 1
            if not pd.read_parquet(fa[k]).equals(pd.read_parquet(fb[k])):
                differ.append(k)
        else:
            n_text += 1
            if fa[k].read_bytes() != fb[k].read_bytes():
                differ.append(k)
    ok = not (differ or only_a or only_b)
    L = ["# Determinism check: two clean runs", "",
         f"Generated by `dcfootprint/experiments/determinism_check.py`. Compared {n_text} text files (byte for byte) "
         f"and {n_pq} parquet tables (as tables). Figures are not compared.", "",
         f"**Result: {'identical' if ok else 'DIFFERENT'}.** Files that differ: {len(differ)}; only in run 1: "
         f"{len(only_a)}; only in run 2: {len(only_b)}."]
    for title, xs in (("Differ", differ), ("Only in run 1", only_a), ("Only in run 2", only_b)):
        if xs:
            L += ["", f"## {title}", ""] + [f"- `{x}`" for x in xs]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return ok


if __name__ == "__main__":
    sys.exit(0 if main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])) else 1)
